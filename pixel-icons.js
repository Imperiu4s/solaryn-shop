  // PP-csomag képe: minél több a pont, annál nagyobb a halom
  window.pxCoinPile = (short) => {
    const n = parseInt(String(short).replace(/[^0-9]/g, ''), 10) || 0;
    const tiers = [[2], [2, 3], [3, 4, 2], [4, 6, 4, 2], [3, 6, 8, 5, 3], [4, 7, 10, 8, 5, 3]];
    const t = n < 2500 ? 0 : n < 4500 ? 1 : n < 8000 ? 2 : n < 16000 ? 3 : n < 32000 ? 4 : 5;
    const stacks = tiers[t];
    const w = 8, h = 3;
    const width = 72, height = 40;
    const totalW = stacks.length * (w + 1) - 1;
    let out = '';
    stacks.forEach((count, i) => {
      const x = Math.round((width - totalW) / 2 + i * (w + 1));
      for (let c = 0; c < count; c++) {
        const y = height - 2 - (c + 1) * h;
        out += '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="' + h + '" fill="var(--gold)"/>'
          + '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="1" fill="var(--gold-hi)"/>'
          + '<rect x="' + x + '" y="' + (y + h - 1) + '" width="' + w + '" height="1" fill="var(--gold-lo)"/>'
          + '<rect x="' + (x + w - 1) + '" y="' + y + '" width="1" height="' + h + '" fill="var(--gold-lo)"/>';
      }
    });
    const shine = t >= 3 ? '<rect x="' + (width / 2 + 12) + '" y="6" width="1" height="5" fill="#fff"/><rect x="' + (width / 2 + 10) + '" y="8" width="5" height="1" fill="#fff"/>' : '';
    return '<svg class="pkg-pile" viewBox="0 0 ' + width + ' ' + height + '" aria-hidden="true" shape-rendering="crispEdges">' + out + shine + '</svg>';
  };
