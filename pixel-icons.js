  const cache = {};
  function build(name) {
    const src = I[name];
    if (!src) return '';
    const rows = src.trim().split('\n');
    const paths = { '#': '', o: '', '*': '' };
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        const c = row[x];
        if (paths[c] === undefined) { x++; continue; }
        let e = x;
        while (e + 1 < row.length && row[e + 1] === c) e++;
        paths[c] += `M${x} ${y}h${e - x + 1}v1h-${e - x + 1}z`;
        x = e + 1;
      }
    });
    return `<svg class="px-ico" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true" focusable="false" shape-rendering="crispEdges">`
      + (paths.o ? `<path fill="currentColor" opacity=".38" d="${paths.o}"/>` : '')
      + (paths['#'] ? `<path fill="currentColor" d="${paths['#']}"/>` : '')
      + (paths['*'] ? `<path fill="var(--ico-accent, var(--gold))" d="${paths['*']}"/>` : '')
      + '</svg>';
  }
  window.pxIcon = (name) => (cache[name] || (cache[name] = build(name)));

